// -----------------------------------------------------------------------
// Writes docs/src/assets/logo-{light,dark}.svg from the SAME geometry the app's
// header uses - ../../src/assets/geo/logo.generated.ts.
//
// Two files rather than one because Starlight renders the logo as an <img>,
// and an <img> inherits nothing from the page: no custom properties, no
// currentColor, no @media query of ours. So each theme's stroke has to be
// baked in, and the values below are --rv-line out of each half of
// ../../src/styles/base/_theme.scss.
//
// Regenerate with `npm run logo:build` after the wordmark's geometry changes.
// Don't hand-edit the output.
// -----------------------------------------------------------------------

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, '../../src/assets/geo/logo.generated.ts');
const outDir = resolve(here, '../src/assets');

// The mark is three concentric copies of the continent, scaled about its own
// centre - it reads as a signal radiating out from Africa. Same three scales
// as components/LogoMap.
const RINGS = [1, 0.75, 0.5];

// --rv-line, light theme then dark. The line that means something.
const STROKE = { light: '#05578d', dark: '#5ea0cc' };

/**
 * The generated module is TypeScript, and this script is plain Node. Rather
 * than pull in a transpiler for three constants, read them out with regexes -
 * the file is machine-written, so its shape is fixed and it cannot drift into
 * something these stop matching without build-geo.mjs changing first.
 */
function extract(ts) {
  const size = ts.match(/LOGO_SIZE\s*=\s*(\d+)/);
  const path = ts.match(/LOGO_AFRICA_PATH\s*=\s*\n?\s*'([^']+)'/);
  const center = ts.match(/LOGO_AFRICA_CENTER[^=]*=\s*\[\s*([\d.]+),\s*([\d.]+),?\s*\]/);

  if (!size || !path || !center) {
    throw new Error(
      `build-logo: could not read the mark out of ${source}. ` +
        'It is generated by scripts/build-geo.mjs - if that script changed shape, this one has to follow.'
    );
  }

  return {
    size: Number(size[1]),
    path: path[1],
    center: [Number(center[1]), Number(center[2])],
  };
}

function toSvg({ size, path, center }, stroke) {
  const [cx, cy] = center;
  const rings = RINGS.map((scale) => {
    const transform =
      scale === 1 ? '' : ` transform="translate(${cx},${cy}) scale(${scale}) translate(${-cx},${-cy})"`;
    return `  <path d="${path}" fill="none" stroke="${stroke}" stroke-width="12"${transform}/>`;
  }).join('\n');

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" width="32" height="32" role="img" aria-label="Rovie">\n${rings}\n</svg>\n`;
}

const mark = extract(await readFile(source, 'utf8'));
await mkdir(outDir, { recursive: true });

for (const [theme, stroke] of Object.entries(STROKE)) {
  const file = resolve(outDir, `logo-${theme}.svg`);
  await writeFile(file, toSvg(mark, stroke), 'utf8');
  console.log(`wrote ${file}`);
}
