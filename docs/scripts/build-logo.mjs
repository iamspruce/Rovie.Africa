// -----------------------------------------------------------------------
// Writes docs/src/assets/logo-{light,dark}.svg from the SAME artwork the app's
// header uses - ../../src/assets/logo.generated.ts, which is itself baked from
// public/logos/*.svg by ../../scripts/build-logo.mjs.
//
// Two files rather than one because Starlight renders the logo as an <img>,
// and an <img> inherits nothing from the page: no custom properties, no
// currentColor, no @media query of ours. So each theme's ink has to be baked
// in - which is the one place on either site that the brand's own "-inverted"
// variant idea is actually needed. The app never loads those files because its
// logo is inlined and can use currentColor; this one cannot.
//
// The mark only. The "Rovie docs" beside it is Starlight's own title text and
// picks up the face from src/styles/rovie.css, so baking the wordmark in here
// would draw it twice.
//
// Regenerate with `npm run logo:build` after the artwork changes. Don't
// hand-edit the output.
// -----------------------------------------------------------------------

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, '../../src/assets/logo.generated.ts');
const outDir = resolve(here, '../src/assets');

// --rv-text out of each half of ../../src/styles/base/_theme.scss. The mark
// used to be stroked in --rv-line, the brand blue, on both themes; it takes
// the text colour now for the same reason the app's header logo does - the
// header reads as one object with the title beside it rather than as a blue
// badge next to black type.
const INK = { light: '#201d1d', dark: '#fdfcfc' };

/**
 * The generated module is TypeScript, and this script is plain Node. Rather
 * than pull in a transpiler for four constants, read them out with regexes -
 * the file is machine-written, so its shape is fixed and it cannot drift into
 * something these stop matching without ../../scripts/build-logo.mjs changing
 * first.
 */
function extract(ts) {
  const viewBox = ts.match(/MARK_VIEWBOX\s*=\s*'([^']+)'/);
  const transform = ts.match(/MARK_TRANSFORM\s*=\s*'([^']+)'/);
  const strokeWidth = ts.match(/MARK_STROKE_WIDTH\s*=\s*([\d.]+)/);
  const block = ts.match(/MARK_PATHS[^=]*=\s*\[([\s\S]*?)\];/);

  if (!viewBox || !transform || !strokeWidth || !block) {
    throw new Error(
      `build-logo: could not read the mark out of ${source}. ` +
        'It is generated by ../../scripts/build-logo.mjs - if that script changed shape, this one has to follow.'
    );
  }

  const paths = [...block[1].matchAll(/'([^']+)'/g)].map((m) => m[1]);
  if (!paths.length) throw new Error('build-logo: MARK_PATHS is empty');

  return {
    viewBox: viewBox[1],
    transform: transform[1],
    strokeWidth: Number(strokeWidth[1]),
    paths,
  };
}

function toSvg({ viewBox, transform, strokeWidth, paths }, ink) {
  const body = paths.map((d) => `    <path d="${d}"/>`).join('\n');

  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" width="32" height="32" role="img" aria-label="Rovie">\n` +
    `  <g transform="${transform}" fill="none" stroke="${ink}" stroke-width="${strokeWidth}" stroke-linejoin="round">\n` +
    `${body}\n` +
    `  </g>\n` +
    `</svg>\n`
  );
}

const mark = extract(await readFile(source, 'utf8'));
await mkdir(outDir, { recursive: true });

for (const [theme, ink] of Object.entries(INK)) {
  const file = resolve(outDir, `logo-${theme}.svg`);
  await writeFile(file, toSvg(mark, ink), 'utf8');
  console.log(`wrote ${file}`);
}
